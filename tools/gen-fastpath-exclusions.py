"""Generate native/kspcfg/src/fastpath_exclusions.rs from allowlist test output.

The fast-path allowlist in kspcfg is a conservative list of script ranges. KSP's Mono runtime uses older
collation tables than desktop .NET, so some characters inside those ranges are treated as ignorable by the
culture-sensitive search stock KSP uses to find `//`, `{` and `}`. Those code points are found empirically and
excluded here:

    monohost --ksp <KSP> -- tests/out/FastBoot.Tests.exe allowlist --ksp <KSP> --dist dist --out mono.txt
    FastBoot.Tests.exe allowlist --ksp <KSP> --dist dist --out clr.txt          (desktop .NET, optional)
    python tools/gen-fastpath-exclusions.py mono.txt [clr.txt ...]

Each input has one hex code point per line. Inputs are merged with the existing table, so exclusions are never
lost when the table is regenerated after they took effect.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "native", "kspcfg", "src", "fastpath_exclusions.rs")


def existing():
    if not os.path.exists(TABLE):
        return set()
    points = set()
    for lo, hi in re.findall(r"\(0x([0-9A-F]+), 0x([0-9A-F]+)\)", open(TABLE, encoding="utf-8").read()):
        points.update(range(int(lo, 16), int(hi, 16) + 1))
    return points


def ranges(points):
    out = []
    for p in sorted(points):
        if out and p == out[-1][1] + 1:
            out[-1][1] = p
        else:
            out.append([p, p])
    return out


def main(paths):
    points = existing()
    for path in paths:
        for line in open(path, encoding="utf-8-sig"):
            line = line.strip()
            if line:
                points.add(int(line, 16))
    rs = ranges(points)
    body = "\n".join("    (0x%04X, 0x%04X)," % (lo, hi) for lo, hi in rs)
    text = (
        "// Generated by tools/gen-fastpath-exclusions.py; do not edit by hand.\n"
        "//\n"
        "// Code points inside the fast-path ranges that KSP's Mono (or desktop .NET) treats differently from an\n"
        "// ordinal search next to `//`, `{` or `}`, found by the allowlist test. Sorted, non-overlapping, inclusive.\n"
        "pub(crate) const EXCLUDED: &[(u32, u32)] = &[\n" + body + "\n];\n"
    )
    open(TABLE, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %d code points in %d ranges to %s" % (len(points), len(rs), TABLE))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1:])
